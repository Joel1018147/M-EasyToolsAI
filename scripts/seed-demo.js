/* ═══════════════════════════════════════════════════════════════════════════
   scripts/seed-demo.js — build a showcase workspace, through the real API
   ───────────────────────────────────────────────────────────────────────────
   Creates one account and fills it with content that is coherent across every
   module, so the product demonstrates its own thinking rather than just
   showing populated tables.

     node scripts/seed-demo.js --url https://… --email … --password …

   ── EVERY ROW GOES THROUGH THE REAL ENDPOINTS ─────────────────────────────
   Nothing here talks to PostgreSQL. It registers over /auth/register, holds a
   real session cookie, and POSTs to the same routes the browser uses — so
   every validator, every owner-scoping rule and every guard runs exactly as
   it does for a customer. A seeder that writes straight to the database can
   create rows the application would have refused, and then the demo is
   showing a state the product cannot actually reach.

   On this platform that is not merely a principle, it is the only option:
   DATABASE_URL points at `postgres.railway.internal`, which resolves only
   inside Railway. There is no direct-write shortcut to be tempted by.

   ── THE CONTENT IS REAL, NOT LOREM ────────────────────────────────────────
   Every document is generated by the live model through POST /api/generate,
   which means every word_count, seo_score and readability figure on the
   dashboard was computed from text the product actually produced. Seeding
   pre-written strings through POST /api/documents would leave seo_score at 0
   on every row — a quality dashboard reading zero everywhere demonstrates
   nothing except that the column exists.

   It also means the trilingual work is demonstrated rather than asserted:
   the Chinese documents carry real four-hundred-word counts, which is the
   whole point of UPGRADE-SPEC §0.7. Before this round they would every one
   have read `1`.

   ── BUILT BACKWARDS FROM WHAT M-Ai NOTICES ────────────────────────────────
   M-Ai has 18 tools and they are only interesting if the data gives them
   something to say. So the fixture is designed against them:

     · documents spread over 7 tool_ids     -> documents_by_tool
     · deliberate long/short mix            -> document_quality_scores spread,
                                               and low_scoring_documents fires
     · three languages                      -> the trilingual story, and the
                                               CJK counter visibly working
     · two PR releases, one draft one not   -> pr_release_pipeline
     · brand profile filled                 -> brand_profile

   ── IT IS OBVIOUSLY A DEMO ────────────────────────────────────────────────
   One fictional Malaysian SME. Suria Teknologi Sdn Bhd does not exist, the
   email domain is a reserved `.example.com`, and nothing here should ever be
   mistaken for a real customer's records.
   ═══════════════════════════════════════════════════════════════════════════ */

