/* ── transport ───────────────────────────────────────────────────────────── */
function req(method, path, body) {
  return new Promise((resolve, reject) => {
    const u = new URL(path, BASE);
    const lib = u.protocol === 'https:' ? https : http;
    const payload = body === undefined ? null : Buffer.from(JSON.stringify(body));
    const r = lib.request({
      hostname: u.hostname,
      port: u.port || (u.protocol === 'https:' ? 443 : 80),
      path: u.pathname + u.search,
      method,
      headers: {
        ...(cookie ? { Cookie: cookie } : {}),
        ...(payload ? { 'Content-Type': 'application/json', 'Content-Length': payload.length } : {}),
        Accept: 'application/json',
      },
      timeout: 240000,
    }, (res) => {
      const sc = res.headers['set-cookie'];
      if (sc) cookie = sc.map((c) => c.split(';')[0]).join('; ');
      /* COLLECT BUFFERS, DECODE ONCE.
         `data += chunk` decodes each chunk as UTF-8 independently, so a
         multi-byte character that straddles a chunk boundary is destroyed —
         the two halves each decode to U+FFFD. On an EN-only payload you would
         never notice. This script generates Chinese, where every character is
         three bytes, and it showed up immediately: a product description read
         back as `拥有大面积���顶` instead of `屋顶`.

         The database was fine — verified by fetching the same row with curl
         and counting zero U+FFFD. The corruption existed only in what this
         script printed, which is the more dangerous kind: it would have been
         read as evidence that the platform mangles Chinese. */
      const chunks = [];
      res.on('data', (d) => { chunks.push(d); });
      res.on('end', () => {
        const data = Buffer.concat(chunks).toString('utf8');
        let json = null;
        try { json = JSON.parse(data); } catch { /* html or empty; status is the signal */ }
        resolve({ status: res.statusCode, body: json, raw: data.slice(0, 300) });
      });
    });
    r.on('timeout', () => r.destroy(new Error('timeout')));
    /* A TRANSPORT ERROR IS A RESULT, NOT AN EXCEPTION.
       The first run of this script died on `read ECONNRESET` five documents
       in: the retry loop below only understood HTTP status codes, so a socket
       the proxy dropped mid-generation rejected the promise and took the whole
       seed with it — leaving a half-populated workspace, which is the exact
       failure mode this script exists to avoid.
       Long generations are precisely when the connection is most likely to be
       cut, so this is the common case, not the edge one. Resolve with status 0
       and let the caller's retry policy decide. */
    r.on('error', (err) => resolve({ status: 0, body: null, raw: String(err.message || err) }));
    if (payload) r.write(payload);
    r.end();
  });
}

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

/* Groq's preview tier rate-limits hard, and a 429 mid-seed would leave a
   half-populated workspace that looks like a product defect rather than a
   throttle. Retry with a widening gap, and give up loudly rather than
   silently skipping a document. */
async function generate(payload, label) {
  for (let attempt = 1; attempt <= 5; attempt++) {
    const r = await req('POST', '/api/generate', payload);
    if (r.status === 200 && r.body && r.body.success) return r.body;
    // status 0 is a dropped socket — see req()'s error handler. It is the most
    // retryable thing here, not the least.
    const retryable = r.status === 0 || r.status === 429 || r.status >= 500;
    if (!retryable || attempt === 5) {
      failures.push(`${label}: HTTP ${r.status} ${(r.body && r.body.error) || r.raw}`);
      return null;
    }
    const wait = attempt * 20000;
    console.log(`      throttled (${r.status}) — waiting ${wait / 1000}s then retrying`);
    await sleep(wait);
  }
  return null;
}

