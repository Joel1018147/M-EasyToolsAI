/* ── run ─────────────────────────────────────────────────────────────────── */
async function main() {
  if (!EMAIL || !PASSWORD) {
    console.error('--email and --password are required');
    process.exit(1);
  }
  console.log('\nSeeding demo workspace');
  console.log('  target : ' + BASE);
  console.log('  account: ' + EMAIL + '\n');

  /* 1. account — register, or sign in if it already exists (idempotent) */
  console.log('1. account');
  let r = await req('POST', '/auth/register', { name: NAME, email: EMAIL, password: PASSWORD });
  if (r.status === 200 || r.status === 201) {
    console.log('   ✓ registered');
  } else {
    console.log('   · register said ' + r.status + ' (' + ((r.body && r.body.error) || '').slice(0, 60) + ') — signing in instead');
    r = await req('POST', '/auth/login', { email: EMAIL, password: PASSWORD });
    if (r.status !== 200) {
      console.error('   ✗ could not register OR sign in: ' + r.status + ' ' + r.raw);
      process.exit(1);
    }
    console.log('   ✓ signed in to the existing account');
  }

  const me = await req('GET', '/auth/me');
  if (me.status !== 200) { console.error('   ✗ no session after auth: ' + me.status); process.exit(1); }
  console.log('   ✓ session held');

  /* 2. brand profile — this is what steers every generation below */
  console.log('\n2. brand profile');
  r = await req('PUT', '/api/auth/me', {
    name: NAME,
    brand_name: COMPANY,
    brand_desc: 'Suria Teknologi Sdn Bhd installs rooftop solar and IoT energy monitoring for Malaysian small and medium businesses — factories, warehouses and cold-storage operators in Selangor and Johor. We sell measurable savings on the electricity bill, not panels. Customers are practical owner-operators who care about payback period, NEM credits and whether the system keeps working in year eight.',
    brand_tone: 'Professional',
  });
  console.log(r.status === 200 ? '   ✓ brand set — every generation below inherits it' : '   ✗ brand ' + r.status);

  /* 3. content — real generations, real scores */
  console.log('\n3. content (live model — this is the slow part)');
  if (FROM > 0) console.log(`   resuming at index ${FROM}; ${FROM} earlier document(s) already exist`);
  for (let di = FROM; di < DOCS.length; di++) {
    const d = DOCS[di];
    const label = `${di}. ${d.lang}/${d.toolId}`;
    process.stdout.write(`   ${label.padEnd(26)}`);
    const out = await generate({
      prompt: d.prompt,
      toolId: d.toolId,
      toolName: d.toolName,
      tone: 'Professional',
      variants: 1,
      lang: d.lang,
    }, label);
    if (out) {
      made.documents++;
      const verified = out.langVerified === false ? ' ⚠ langVerified=false' : '';
      console.log(`✓ ${String(out.wordCount).padStart(4)} words · seo ${String(out.seoScore).padStart(3)} · read ${String(out.readability).padStart(3)}${verified}`);
    } else {
      console.log('✗');
    }
    await sleep(4000); // pace against the preview-tier rate limit
  }

  /* 4. PR releases */
  console.log('\n4. press releases');
  for (const p of PR) {
    process.stdout.write(`   ${p.headline.slice(0, 46).padEnd(48)}`);
    /* SAME RETRY AS THE DOCUMENTS, and it was missing here on the first run.
       Both press releases failed with 500, and the production log showed why:
         Rate limit reached ... TPM: Limit 8000, Used 6947, Requested 3359
       Groq's free tier allows 8,000 tokens per minute and a press release
       asks for ~3,300 on top of whatever the previous document just spent.
       The documents survived it because they retried; these did not, because
       I wrote a bare request here. Not a product defect — a gap in the seeder. */
    let rr = null;
    for (let attempt = 1; attempt <= 6; attempt++) {
      rr = await req('POST', '/api/pr/generate', p);
      if (rr.status === 200 && rr.body && rr.body.success !== false) break;
      const retryable = rr.status === 0 || rr.status === 429 || rr.status >= 500;
      if (!retryable || attempt === 6) break;
      const wait = 25000 + attempt * 10000;
      console.log(`\n      throttled (${rr.status}) — waiting ${wait / 1000}s then retrying`);
      await sleep(wait);
      process.stdout.write(`   ${'retry'.padEnd(48)}`);
    }
    if (rr && rr.status === 200 && rr.body && rr.body.success !== false) {
      made.pr++;
      const g = rr.body.geoScore !== undefined ? ` · geo ${rr.body.geoScore}` : '';
      console.log(`✓ ${String(rr.body.wordCount || '?').padStart(4)} words${g}`);
    } else {
      failures.push(`PR "${p.headline.slice(0, 30)}": ${rr.status} ${(rr.body && rr.body.error) || rr.raw}`);
      console.log('✗ ' + rr.status);
    }
    await sleep(6000);
  }

  /* 5. images — real Qwen generations, re-hosted by the platform */
  if (SKIP_IMAGES) {
    console.log('\n5. images — skipped (--skip-images)');
  } else {
    console.log('\n5. images (live Qwen-Image, downloaded and re-hosted)');
    for (const im of IMAGES) {
      process.stdout.write(`   ${im.size.padEnd(12)}${im.prompt.slice(0, 40).padEnd(42)}`);
      const ir = await req('POST', '/api/images/generate', im);
      if (ir.status === 201 && ir.body && ir.body.image) {
        made.images++;
        const img = ir.body.image;
        console.log(`✓ ${img.status} · ${img.byte_size ? Math.round(img.byte_size / 1024) + 'KB' : '?'}`);
      } else {
        failures.push(`image ${im.size}: ${ir.status} ${(ir.body && (ir.body.message || ir.body.error)) || ir.raw}`);
        console.log('✗ ' + ir.status + ' ' + String((ir.body && (ir.body.reason || ir.body.error)) || '').slice(0, 40));
      }
      await sleep(3000);
    }
  }

  /* 6. what the workspace actually holds now */
  console.log('\n6. verification — reading it back through the API');
  const stats = await req('GET', '/api/stats');
  if (stats.status === 200) console.log('   /api/stats  ' + JSON.stringify(stats.body));
  const docs = await req('GET', '/api/documents/');
  const sub = await req('GET', '/api/subscription/status');
  if (sub.status === 200) console.log('   subscription ' + JSON.stringify(sub.body).slice(0, 160));

  console.log('\n─────────────────────────────────────────────');
  console.log(`  documents generated : ${made.documents}/${DOCS.length}`);
  console.log(`  press releases      : ${made.pr}/${PR.length}`);
  console.log(`  images              : ${made.images}/${SKIP_IMAGES ? 0 : IMAGES.length}`);
  if (failures.length) {
    console.log(`\n  ${failures.length} failure(s) — NOT hidden:`);
    failures.forEach((f) => console.log('    · ' + f));
  } else {
    console.log('\n  no failures');
  }
  console.log('');
}

main().catch((e) => { console.error('\nFATAL: ' + e.message); process.exit(1); });
